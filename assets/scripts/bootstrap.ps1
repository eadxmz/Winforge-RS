# C:\Temp\WinForge\bootstrap.ps1
$ErrorActionPreference = "SilentlyContinue"
Write-Host "=== WinForge Post-Install Provisioning ===" -ForegroundColor Cyan

# 1. Unlock & Activate Ultimate Performance Power Plan (Works on Win10, Win11, and LTSC)
Write-Host "[1/4] Activating Ultimate Performance Power Plan..."
$ultScheme = "e9a42b02-d5df-448d-aa00-03f14749eb61"
$dupOutput = powercfg /duplicatescheme $ultScheme
if ($dupOutput -match "([a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12})") {
    powercfg /setactive $matches[1]
}
# Disable hibernate & standby timeouts on AC power
powercfg /change monitor-timeout-ac 0
powercfg /change standby-timeout-ac 0
powercfg /hibernate off

# 2. Install Offline Bundled Apps (From manifest.json generated by Rust)
Write-Host "[2/4] Installing Bundled Offline Applications..."
$manifestPath = "C:\Temp\WinForge\apps\manifest.json"
if (Test-Path $manifestPath) {
    $apps = Get-Content $manifestPath | ConvertFrom-Json
    foreach ($app in $apps) {
        Write-Host " -> Installing $($app.Name)..."
        Start-Process -FilePath $app.InstallerPath -ArgumentList $app.SilentArgs -Wait -NoNewWindow
    }
}

# 3. Apply Exported CTT (Chris Titus Tech WinUtil) Config Offline
# Note: Rust downloads the raw winutil.ps1 script during ISO creation so no internet is needed!
$cttScript = "C:\Temp\WinForge\configs\winutil.ps1"
$cttConfig = "C:\Temp\WinForge\configs\ctt_export.json"
if ((Test-Path $cttScript) -and (Test-Path $cttConfig)) {
    Write-Host "[3/4] Applying Chris Titus WinUtil Tweaks..."
    & $cttScript -Config $cttConfig -Run
}

# 4. Apply Exported Winhance Registry & PowerShell Tweaks
$winhanceReg = Get-ChildItem "C:\Temp\WinForge\configs\*.reg"
foreach ($reg in $winhanceReg) {
    Write-Host " -> Importing Registry Tweak: $($reg.Name)"
    reg import $reg.FullName
}

$winhancePs1 = "C:\Temp\WinForge\configs\winhance_export.ps1"
if (Test-Path $winhancePs1) {
    Write-Host "[4/4] Applying Winhance Script Tweaks..."
    & $winhancePs1
}

# Cleanup staging folder
Remove-Item "C:\Temp\WinForge" -Recurse -Force
Write-Host "Provisioning Complete!" -ForegroundColor Green
